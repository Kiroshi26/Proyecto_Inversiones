SELECT
    ANOTER AS ANIO,
    CONTER AS CONTABILIDAD,
    CTATER AS CUENTA,
    INITER AS SALDO_INICIAL,
    (ENDTER + FEDTER + MADTER + ABDTER + MYDTER + JUDTER + JLDTER + AGDTER + SEDTER + OCDTER + NODTER + DIDTER) AS DEBITOA,
    (ENCTER + FECTER + MACTER + ABCTER + MYCTER + JUCTER + JLCTER + AGCTER + SECTER + OCCTER + NOCTER + DICTER) AS CREDITOA,
    (INITER + (ENDTER - ENCTER) + (FEDTER - FECTER) + (MADTER - MACTER) + (ABDTER - ABCTER) + (MYDTER - MYCTER) + (JUDTER - JUCTER) + (JLDTER - JLCTER) + (AGDTER - AGCTER) + (SEDTER - SECTER) + (OCDTER - OCCTER) + (NODTER - NOCTER) + (DIDTER - DICTER)) AS SALDO_FINAL_ACUM,
    (INITER + (ENDTER - ENCTER) + (FEDTER - FECTER) + (MADTER - MACTER) + (ABDTER - ABCTER) + (MYDTER - MYCTER) + (JUDTER - JUCTER) + (JLDTER - JLCTER) + (AGDTER - AGCTER) + (SEDTER - SECTER) + (OCDTER - OCCTER) + (NODTER - NOCTER)) AS SALDO_ANTERIOR,
    DIDTER AS DEBITOM,
    DICTER AS CREDITOM,
    (INITER + (ENDTER - ENCTER) + (FEDTER - FECTER) + (MADTER - MACTER) + (ABDTER - ABCTER) + (MYDTER - MYCTER) + (JUDTER - JUCTER) + (JLDTER - JLCTER) + (AGDTER - AGCTER) + (SEDTER - SECTER) + (OCDTER - OCCTER) + (NODTER - NOCTER) + (DIDTER - DICTER)) AS TOTAL_MES
FROM FOPLIBNOR3.SCTATER A
LEFT JOIN FOPLIBNOR3.TERCER B
    ON A.TERTER = B.CODTER
WHERE ANOTER = 2025
    AND CTATER LIKE '13%'
    AND (INITER + (ENDTER - ENCTER) + (FEDTER - FECTER) + (MADTER - MACTER) + (ABDTER - ABCTER) + (MYDTER - MYCTER) + (JUDTER - JUCTER) + (JLDTER - JLCTER) + (AGDTER - AGCTER) + (SEDTER - SECTER) + (OCDTER - OCCTER) + (NODTER - NOCTER) + (DIDTER - DICTER)) <> 0